// Сесія віддаленого керування: режим (WiFi/BT/Off), генерація PIN, автентифікація.
// Незалежна від транспорту й від заліза — RNG підключається хуком (esp_random на
// пристрої, детермінований мок у тестах). Чистий шар, тестується на хості.
//
// Модель загрози: PIN — слабкий бар'єр "потрібен фізичний доступ до екрана", не
// криптографія. Тому ОБОВ'ЯЗКОВИЙ rate-limit на невдалі спроби.
#pragma once
#include <stdint.h>

enum RemoteMode : uint8_t {
  MODE_OFF = 0,
  MODE_WIFI,
  MODE_BT
};

enum AuthResult : uint8_t {
  AUTH_OK = 0,      // PIN вірний, сесія автентифікована
  AUTH_WRONG,       // PIN невірний, спроби ще лишились
  AUTH_LOCKED       // вичерпано ліміт спроб — транспорт має розірвати з'єднання
};

// Ліміт невдалих спроб PIN до блокування (rate-limit).
static const int SESSION_MAX_ATTEMPTS = 5;

// Хук джерела випадковості. Пристрій ставить esp_random; тест — свій генератор.
// За замовчуванням — детермінований fallback (щоб не було 0 без встановлення).
void session_set_rng(uint32_t (*rng)());

// Скидає все у вихідний стан (режим OFF, без PIN, лічильники нуль).
void session_init();

// Перемикає режим. При переході в WiFi/BT: генерує НОВИЙ PIN і скидає авторизацію
// (новий режим завжди вимикає попередній — активним лишається тільки один).
// При OFF: очищає PIN і авторизацію.
void session_set_mode(RemoteMode mode);

RemoteMode session_active_mode();

// Поточний 6-значний PIN (з провідними нулями). "" якщо режим OFF.
const char* session_pin();

// Примусово встановлює PIN (замість щойно згенерованого) — для персистентного PIN
// (той самий після кожного рестарту). Приймає лише валідний 6-значний рядок, інакше
// ігнорує. Викликати ОДРАЗУ після session_set_mode(), поки режим не OFF.
void session_set_pin(const char* pin);

// Чи автентифікована поточна сесія.
bool session_is_authenticated();

// Перевіряє PIN клієнта. Веде лічильник невдалих спроб; після SESSION_MAX_ATTEMPTS
// повертає AUTH_LOCKED. Вірний PIN -> AUTH_OK і сесія автентифікована.
AuthResult session_authenticate(const char* pin);

// Скидає стан авторизації для НОВОГО клієнтського з'єднання (лічильник спроб,
// прапорець автентифікації) — але НЕ змінює режим і PIN.
void session_reset_auth();

// Примусова автентифікація для ДОВІРЕНОГО транспорту (USB-кабель = фізичний доступ,
// сильніший за PIN). Якщо режим OFF — вмикає WiFi-режим (генерує PIN), щоб handler'и,
// які читають режим/PIN, працювали. Не для мережевих клієнтів.
void session_force_auth();
