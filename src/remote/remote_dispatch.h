// Диспетчер вхідних повідомлень від транспорту (WiFi/BT) — авторизаційний бар'єр.
// Звязує protocol + session + input_queue в одному місці; транспорти лише
// передають сирий JSON-рядок сюди. Чистий шар — тестується на хості.
//
// Правило (розділ 3): доки сесія не автентифікована, перше й єдине прийнятне
// повідомлення — {"pin":"..."}. Жодні btn/text до auth у чергу НЕ потрапляють.
#pragma once
#include <stdint.h>

enum RemoteAction : uint8_t {
  RA_NONE = 0,       // нічого особливого, продовжуй
  RA_DISCONNECT      // транспорт має розірвати з'єднання (вичерпано спроби PIN)
};

// Обробляє один сирий вхідний JSON-рядок від клієнта. Повертає дію для транспорту.
RemoteAction remote_handle_incoming(const char* json);
