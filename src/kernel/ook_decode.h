// Чистий декодер OOK/ASK-пультів (сімейство EV1527 / PT2262 — 24-бітний PWM).
// Вхід — масив тривалостей імпульсів у мкс, що чергуються mark(HIGH)/space(LOW),
// починаючи з mark. БЕЗ апаратних включень -> native-тести. Захоплення таймінгу
// (RMT на GDO0) робить драйвер CC1101 і подає сюди готовий масив.
//
// Формат EV1527/PT2262: базовий інтервал Te. Біт "0" = HIGH 1·Te + LOW 3·Te;
// біт "1" = HIGH 3·Te + LOW 1·Te. Синхро = HIGH 1·Te + LOW ~31·Te (довга пауза).
// 24 біти на кадр (у EV1527: 20 біт адреси + 4 біти даних).
#pragma once
#include <stdint.h>

struct OokDecoded {
  bool        valid;     // чи розпізнано повний 24-бітний кадр
  const char* proto;     // "EV1527/PT2262" або "?"
  uint32_t    code;      // декодовані біти, вирівняні праворуч (до 24 біт)
  int         bits;      // к-ть декодованих біт (24 при valid)
  int         te_us;     // оцінений базовий інтервал Te (мкс)
};

// Декодує перший повний кадр із масиву pulses[0..n-1] (мкс, mark/space з mark).
// Не знайдено валідного кадру -> {valid=false}.
OokDecoded ook_decode(const uint16_t* pulses, int n);
