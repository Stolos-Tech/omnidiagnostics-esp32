// Чиста логіка суб-ГГц радіо (CC1101) — БЕЗ апаратних включень, тож іде в native-тести.
// Математика частот під кварц 26 МГц, конвертація RSSI в dBm, план свіпу по трьох
// перестроюваних вікнах CC1101 і набір популярних ISM-частот для захоплення.
#pragma once
#include <stdint.h>

// Кварц CC1101 (кГц). Частотний крок = f_xtal / 2^16.
#define SUBGHZ_XTAL_KHZ 26000

// --- План свіпу спектра ---------------------------------------------------------
// CC1101 перестроюється ЛИШЕ в три вікна (300-348 / 387-464 / 779-928 МГц); поза
// ними PLL не залочиться -> RSSI був би сміттям. Тому свіп проходить лише по цих
// вікнах з кроком 2 МГц (без «мертвих» стовпчиків у проміжках). Індекс 0..count-1
// логічно неперервний; частота й вікно беруться з функцій нижче.
int  subghz_scan_count();          // к-ть точок свіпу (сумарно по трьох вікнах)
long subghz_scan_khz(int i);       // частота точки i (кГц); -1 якщо i поза межами
int  subghz_scan_window(int i);    // вікно точки i: 0=A(300-348) 1=B(387-464) 2=C(779-928); -1 oob

// --- Частота <-> регістри FREQ2/FREQ1/FREQ0 ------------------------------------
// FREQ = round(f * 2^16 / f_xtal). Округлення до найближчого.
void subghz_freq_to_regs(long khz, uint8_t* f2, uint8_t* f1, uint8_t* f0);
long subghz_regs_to_khz(uint8_t f2, uint8_t f1, uint8_t f0);

// --- RSSI ----------------------------------------------------------------------
// Сирий регістр RSSI (доповняльний код) -> dBm за формулою CC1101 (offset 74 dB).
int  subghz_rssi_dbm(uint8_t raw);

// --- Хелпери гістограми (RSSI зберігаємо як int8 dBm, -128..0) ------------------
int  subghz_peak_index(const int8_t* dbm, int n);          // індекс найсильнішого (max dBm); -1 якщо n<=0
int  subghz_bar_height(int dbm, int floor_dbm, int top_dbm, int h); // dBm -> висота 0..h

// --- Популярні ISM-частоти для Tier 2 (захоплення) -----------------------------
int         subghz_preset_count();
long        subghz_preset_khz(int i);    // -1 якщо oob
const char* subghz_preset_name(int i);   // напр. "433.92"; "?" якщо oob
