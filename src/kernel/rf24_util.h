// Чиста логіка для 2.4GHz-аналізатора nRF24 (без апаратних включень -> native-тести).
#pragma once
#include <stdint.h>

// Частота каналу nRF24: канал 0..125 -> 2400..2525 МГц (крок 1 МГц). Затискається.
int rf24_channel_mhz(int ch);

// Найближчий WiFi-канал 2.4ГГц (1..14), чий центр у межах ~11 МГц від частоти
// цього nRF-каналу; 0 якщо поза WiFi-смугами. (WiFi ch1=2412 ... ch13=2472,
// ch14=2484; крок 5 МГц, ширина ~22 МГц — тому nRF-активність корисно мапити на WiFi.)
int rf24_wifi_channel(int ch);

// Індекс каналу з максимальним лічильником (перший при рівності); -1 якщо n<=0.
int rf24_peak_index(const uint8_t* counts, int n);

// Висота стовпчика 0..h за лічильником відносно maxv (maxv<=0 або count<=0 -> 0).
int rf24_bar_height(int count, int maxv, int h);
