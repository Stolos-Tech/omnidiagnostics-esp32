// Керування охолодженням: температура плати -> PWM-duty вентилятора, з гістерезисом
// (щоб не «дзижчав» на порозі) і станом захисту від перегріву/тротлінгу. Чистий модуль
// (без апаратних включень) -> native-тести. Реальний вентилятор (5V RPi-fan через
// логічний MOSFET на вільному GPIO) під'єднається пізніше; тут — крива й логіка.
#pragma once

struct CoolingCfg {
  float start_c;   // нижче цього — вентилятор стоїть (напр. 45)
  float full_c;    // вище цього — 100% (напр. 65)
  float hyst_c;    // гістерезис вимикання (напр. 3)
};

// PWM-duty 0..255 за температурою. prev_duty — попередній стан (для гістерезису).
// Вентилятор стартує з MIN-duty (подолати стик), далі лінійно до 255.
int cooling_fan_duty(float temp_c, int prev_duty, const CoolingCfg& cfg);

// Стан для UI/захисту: 0 = OK, 1 = WARN (>=full_c), 2 = CRITICAL (>=crit_c ->
// час знижувати навантаження/CPU, щоб уникнути зависань через перегрів).
int cooling_state(float temp_c, float full_c, float crit_c);
