#pragma once
#include <stdint.h>
// БЕЗПЕЧНИЙ РЕЖИМ ЖИВЛЕННЯ пінів (рантайм, персист у NVS «hwsafe»/«safe», default true).
// g_hw_safe == true:  firmware НЕ жене жоден пін зовнішніх модулів (SPI SCK/MOSI, CS/CSN/CE
//   nRF24/SD/CC1101, UART TX до UNO) — усі у high-Z (INPUT). Голі ніжки без модулів не коротнуть.
//   Дисплей/кнопки/батарея/WiFi — працюють.
// g_hw_safe == false: піни модулів у робочому idle (CS/CSN HIGH, CE low) — АЛЕ лише після
//   КЗ-перевірки (див. нижче).
//
// КЗ-ЗАХИСТ АКТИВАЦІЇ: перед тим як драйвити піни (при активації або на кожному boot, якщо NVS
//   каже active), кожен пін зондуємо pull-up/pull-down toggle. Плаваючий пін (слухає внутрішній
//   pull) — безпечно драйвити. Пін, застряглий на рейці (КЗ на VCC/GND або контеншн) — драйв у
//   протилежний рівень спричинив би КЗ → такий пін НЕ драйвимо, і активацію відкочуємо у safe.
//   g_hw_blocked — бітова маска заблокованих: біт0 nRF CSN(25), 1 SD CS(33), 2 CC1101 CS(27),
//   3 nRF CE(12), 4 SPI-шина(2/15). Примітка: дріт до CMOS-входу модуля НЕ детектується (він
//   high-Z, «плаває») — детектуються саме КЗ на рейку, тобто реальний ризик спалення.
extern bool     g_hw_safe;
extern uint32_t g_hw_blocked;
void hw_safe_begin();       // завантажити g_hw_safe з NVS (не застосовує піни)
void hw_safe_apply_pins();  // safe→high-Z; active→КЗ-перевірка, драйв лише чистих (інакше відкат у safe)
void hw_safe_set(bool safe);// оновити g_hw_safe + персист NVS + застосувати (з КЗ-перевіркою при активації)
