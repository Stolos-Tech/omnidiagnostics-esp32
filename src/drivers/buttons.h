// Апаратний шар вводу: читає GPIO, проганяє через детектори і кладе події в
// спільну чергу ядра (input_queue). Тут — ЛИШЕ дві рідні кнопки T-Display:
//   GPIO35 (права)      -> BTN_S2  (гортання вниз / наступна сторінка), long-press=wake
//   GPIO0  (ліва, BOOT) -> tap=BTN_S5 (вибір), hold=назад
// Джойстик KY-023 (замість колишніх свічів) висить на Arduino UNO і шле навігацію
// по лінку -> її обробляє drivers/uno_link (не цей файл). Обидва джерела -> одна черга.
#pragma once
#include <stdint.h>

void buttons_init();
void buttons_poll(uint32_t now_ms);  // викликати щоциклу в loop(), неблокуючий

// millis() останньої ФІЗИЧНОЇ активності кнопок плати (натиснута зараз або щойно
// відпущена) — незалежно від подій у чергу (ті ж кнопки шле і веб-клієнт через
// input_queue, а це — лише апаратний сигнал, для підсвітки/wake-логіки).
uint32_t buttons_last_activity_ms();

// Одноразовий сигнал: праву кнопку (GPIO35) утримали >=700мс. Повертає true РАЗ
// (по досягненні порогу) і скидається. Використовується для виходу з пасивного
// режиму (екран off) саме довгим правим натиском, а не будь-яким дотиком.
bool buttons_right_longpress();
