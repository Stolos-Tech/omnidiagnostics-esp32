// Register-level драйвер TI CC1101 (суб-ГГц трансивер) на ESP32 — без зовнішньої
// бібліотеки. Спільна HSPI-шина з nRF24/SD (SCK=2, MOSI=15, MISO=38), окремий CS,
// GDO0 для асинхронного OOK-потоку.
//
// ПІНИ (T-Display, розкладка з дорожньої карти CC1101):
//   SCK=GPIO2  MOSI=GPIO15  MISO=GPIO38(input-only, спільний з nRF24 — обидва tri-state)
//   CS =GPIO27 (пожертвуваний свіч BACK; back-жест лишається довгим утриманням лівої)
//   GDO0=GPIO39 (input-only) — асинхронний вихід демодульованих даних для OOK-захоплення
//   Живлення 3.3V. Антена — рідна 868/915 (на 433 працює зблизька, узгодження не те).
//
// РІВНІ ВЕРИФІКАЦІЇ: чиста математика/декод — у kernel/subghz_util + kernel/ook_decode
// (native-тести). Цей файл — апаратний, збирається лише під ttgo; конфіг-регістри OOK —
// стартова точка, можлива підстройка на залізі.
#pragma once
#include <stdint.h>

// Ініт SPI + reset + завантаження базового OOK/ASK-конфігу. Дефолтна частота 433.92 МГц.
// true = модуль відповів (VERSION-регістр валідний).
bool cc1101_begin();

// Дешева перевірка присутності: читає VERSION (0x31), валідний якщо !=0x00 і !=0xFF.
bool cc1101_present();

// Перепрограмувати несучу (кГц) з рекалібруванням (IDLE -> set FREQ -> RX).
void cc1101_set_freq_khz(long khz);

// Один вимір RSSI на частоті khz: IDLE -> FREQ -> RX -> осідання -> читання RSSI.
// Повертає dBm (типово -30..-110). Блокуюче ~1.5 мс.
int cc1101_probe_rssi_dbm(long khz);

// Захоплення OOK-таймінгу на частоті khz через RMT на GDO0 (GPIO39). Заповнює
// pulses[] тривалостями (мкс), що чергуються mark/space починаючи з mark. Повертає
// к-ть імпульсів (0 якщо тиша/таймаут). Блокуюче до timeout_ms.
int cc1101_capture_ook(long khz, uint16_t* pulses, int max_pulses, int timeout_ms);
